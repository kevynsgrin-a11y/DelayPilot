#!/usr/bin/env node
/**
 * generate-security-txt — RFC 9116 disclosure metadata, written from configuration.
 * Owner: seo-engineer (`scripts/seo/**`, `apps/web/public/.well-known/**`).
 *
 * WHY THE FILE IS GENERATED RATHER THAN COMMITTED. RFC 9116 makes exactly two fields mandatory,
 * `Contact` and `Expires`, and DelayPilot can supply neither honestly today. There is no monitored
 * address (owner input I-3, `docs/BUILD_PLAN.md §10`) and an invented one is worse than an absent
 * file: a finder who reports a vulnerability into a mailbox nobody reads believes they have
 * reported it. `Expires` has the same property in the other direction — a date in the past tells a
 * finder the channel is unmaintained — so it is stamped when the file is written rather than typed
 * once and forgotten.
 *
 * So the adapter ships and the file does not. The moment `PUBLIC_CONTACT_EMAIL` is set, one command
 * writes both copies (`AGENTS.md §1.6`: a complete adapter, a validated config contract, an
 * `.env.example` entry, a fail-closed path and documented activation steps).
 *
 * WHAT IT WRITES, AND WHAT IT DELIBERATELY OMITS
 *   Contact               the configured role address, as a `mailto:` URI
 *   Expires               one year from the day it is generated, which RFC 9116 recommends
 *   Preferred-Languages   `en`, which is the only language this site is published in
 *   Canonical             both served locations, so a copy found elsewhere can be recognized
 *   Policy                OMITTED — no disclosure-policy page exists; a link to one that 404s is a
 *                         dead reference (`AGENTS.md §1.6`)
 *   Encryption            OMITTED — no published key exists, and a key nobody holds is worse than
 *                         none
 *   Acknowledgments,
 *   Hiring, CSAF          OMITTED — each would assert a page or a programme that does not exist
 *
 * Usage:
 *   node scripts/seo/generate-security-txt.mjs            # write, or explain why it cannot
 *   node scripts/seo/generate-security-txt.mjs --check    # report the current state, write nothing
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

import { COMMITTED_ORIGIN, normalizeSiteUrl } from '../../apps/web/src/lib/seo/site-url.mjs'

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const PUBLIC = join(repoRoot, 'apps/web/public')
const WELL_KNOWN = join(PUBLIC, '.well-known/security.txt')
const ROOT_COPY = join(PUBLIC, 'security.txt')
const EXPIRY_DAYS = 365

const checkOnly = process.argv.includes('--check')
const configured = normalizeSiteUrl(process.env['PUBLIC_SITE_URL'])
const origin = configured.ok ? configured.origin : COMMITTED_ORIGIN
const rawContact = process.env['PUBLIC_CONTACT_EMAIL']
const contact = typeof rawContact === 'string' ? rawContact.trim() : ''

const present = existsSync(WELL_KNOWN)

if (contact === '') {
  const state = present
    ? `A file exists at ${WELL_KNOWN} but no address is configured; delete it or configure the address it claims.`
    : 'No file is written, which is the designed state.'
  console.log(
    'generate-security-txt: PUBLIC_CONTACT_EMAIL is not set, so there is no monitored address to ' +
      `publish (owner input I-3). ${state}\n` +
      '  RFC 9116 requires a Contact field. An address that reaches nobody would tell a finder ' +
      'their report was received when it was not, so nothing is invented here.',
  )
  process.exit(present ? 1 : 0)
}

if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(contact)) {
  console.error(
    `generate-security-txt: PUBLIC_CONTACT_EMAIL is "${contact}", which is not an address.`,
  )
  process.exit(1)
}

const expires = new Date(Date.now() + EXPIRY_DAYS * 24 * 60 * 60 * 1000)
const expiresIso = `${expires.toISOString().slice(0, 10)}T00:00:00Z`

const body = [
  '# DelayPilot security contact (RFC 9116).',
  '#',
  '# Generated by scripts/seo/generate-security-txt.mjs from PUBLIC_CONTACT_EMAIL. Regenerate',
  '# before the Expires date below: node scripts/seo/test-seo.mjs fails once it is in the past,',
  '# because an expired file tells a finder the channel is unmaintained.',
  '#',
  '# No Policy, Encryption, Acknowledgments, Hiring or CSAF field is published: each would name a',
  '# page, a key or a programme that does not exist.',
  '',
  `Contact: mailto:${contact}`,
  `Expires: ${expiresIso}`,
  'Preferred-Languages: en',
  `Canonical: ${origin}/.well-known/security.txt`,
  `Canonical: ${origin}/security.txt`,
  '',
].join('\n')

if (checkOnly) {
  const current = present ? readFileSync(WELL_KNOWN, 'utf8') : undefined
  const same = current === body
  console.log(
    `generate-security-txt --check: ${present ? 'present' : 'absent'}` +
      `${present ? `, ${same ? 'matches' : 'differs from'} what this script would write now (the Expires stamp moves daily, so a difference is expected unless it was generated today)` : ''}.`,
  )
  process.exit(present ? 0 : 1)
}

mkdirSync(dirname(WELL_KNOWN), { recursive: true })
writeFileSync(WELL_KNOWN, body, 'utf8')
writeFileSync(ROOT_COPY, body, 'utf8')

console.log(
  `generate-security-txt: wrote ${WELL_KNOWN} and ${ROOT_COPY}.\n` +
    `  Contact: mailto:${contact}\n` +
    `  Expires: ${expiresIso}\n` +
    '  Both copies are byte-identical; node scripts/seo/test-seo.mjs asserts that, the required ' +
    'fields, and that the expiry is still in the future.',
)
